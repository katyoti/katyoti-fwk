// ── Combined streaming timeline ──────────────────────────────────────────
// Interleaves MD and HTML chunks to simulate both documents being
// produced concurrently by different agents.

export function buildTimeline(): DocDelta[] {
  const timeline: DocDelta[] = []
  let mi = 0
  let hi = 0

  // Alternate: 2 MD chunks, then 1 HTML chunk, with varying delays.
  while (mi < MD_CHUNKS.length || hi < HTML_CHUNKS.length) {
    // 2 MD chunks
    for (let i = 0; i < 2 && mi < MD_CHUNKS.length; i++, mi++) {
      timeline.push({ delayMs: 150 + Math.random() * 200, docId: 'doc-analysis', delta: MD_CHUNKS[mi] })
    }
    // 1 HTML chunk
    if (hi < HTML_CHUNKS.length) {
      timeline.push({ delayMs: 200 + Math.random() * 300, docId: 'doc-dashboard', delta: HTML_CHUNKS[hi] })
      hi++
    }
  }

  return timeline
}

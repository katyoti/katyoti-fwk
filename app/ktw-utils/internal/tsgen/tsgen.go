// Package tsgen turns a KTSP descriptor into a TYPED TypeScript client that calls
// the GUI's single generic KTSP dispatcher.
//
// Why generate rather than hand-write: the descriptor is the same source the wire
// is built from, so a client generated from it cannot drift. A hand-written TS
// wrapper would be the one-Wails-binding-per-method problem in another language —
// see rule management-plane-hub-authority invariant 5.
//
// The emitted client depends on nothing but a caller-supplied dispatch function,
// so it is framework-agnostic; ktw-gui binds that function to its generic
// CallKTSPMethod Wails binding.
package tsgen

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	mfapi "github.com/katyoti/katyoti-fwk/internal/extensions/manifest/api"
)

// Descriptor is the slice of the describe document we consume. It reuses the
// manifest package's own SlotType, so a change there surfaces here as a compile
// error rather than a silent decode mismatch.
type Descriptor struct {
	Name string `json:"name"`
	KTSP struct {
		Name      string           `json:"name"`
		SlotTypes []mfapi.SlotType `json:"slot_types"`
	} `json:"ktsp"`
}

// Options control one generation pass.
type Options struct {
	// Provider is the wire provider prefix. Defaults to ktsp.name, then name.
	Provider string
	// SlotTypes limits generation to these slot types; empty = all.
	SlotTypes []string
}

// Generate returns one TS module per slot type, keyed by slot-type name.
func Generate(descriptorJSON []byte, opts Options) (map[string]string, error) {
	var d Descriptor
	if err := json.Unmarshal(descriptorJSON, &d); err != nil {
		return nil, fmt.Errorf("parse descriptor: %w", err)
	}
	provider := opts.Provider
	if provider == "" {
		provider = d.KTSP.Name
	}
	if provider == "" {
		provider = d.Name
	}
	if provider == "" {
		return nil, fmt.Errorf("descriptor has no provider name")
	}
	want := map[string]bool{}
	for _, s := range opts.SlotTypes {
		want[s] = true
	}

	out := map[string]string{}
	for _, st := range d.KTSP.SlotTypes {
		if len(want) > 0 && !want[st.Type] {
			continue
		}
		src, err := generateSlot(provider, st)
		if err != nil {
			return nil, fmt.Errorf("slot %q: %w", st.Type, err)
		}
		out[st.Type] = src
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no slot types generated (descriptor has %d)", len(d.KTSP.SlotTypes))
	}
	return out, nil
}

func generateSlot(provider string, st mfapi.SlotType) (string, error) {
	methods := append([]mfapi.SlotMethod(nil), st.Methods...)
	sort.Slice(methods, func(i, j int) bool { return methods[i].Name < methods[j].Name })

	var b strings.Builder
	b.WriteString("// Code generated by: ktw-utils gen-ktsp-client. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n// Source: slot type %q of provider %q.\n", st.Type, provider)
	b.WriteString("// Regenerate after publishing a method; never hand-edit — this file is the\n")
	b.WriteString("// typed face of the wire, and the wire is defined by the service ServiceDef.\n\n")

	b.WriteString("/** Dispatches one KTSP call. ktw-gui binds this to its generic\n")
	b.WriteString(" *  CallKTSPMethod(universe, slotPath, inputJSON) Wails binding. */\n")
	b.WriteString("export type KtspDispatch = (slotPath: string, input: unknown) => Promise<unknown>\n\n")

	for _, m := range methods {
		in, err := typeBlock(exportName(m.Name)+"Input", m.InputSchema)
		if err != nil {
			return "", fmt.Errorf("method %q input: %w", m.Name, err)
		}
		outT, err := typeBlock(exportName(m.Name)+"Output", m.OutputSchema)
		if err != nil {
			return "", fmt.Errorf("method %q output: %w", m.Name, err)
		}
		b.WriteString(in)
		b.WriteString(outT)
	}

	fmt.Fprintf(&b, "/** Typed client for the %q slot. Every method goes through the ONE generic\n", st.Type)
	b.WriteString(" *  dispatcher — publishing a method needs no Go change in ktw-gui. */\n")
	fmt.Fprintf(&b, "export function make%sClient(dispatch: KtspDispatch) {\n", exportName(st.Type))
	b.WriteString("  return {\n")
	for _, m := range methods {
		fn := lowerFirst(exportName(m.Name))
		slotPath := fmt.Sprintf("%s:%s/%s", provider, st.Type, m.Name)
		if m.Description != "" {
			fmt.Fprintf(&b, "    /** %s */\n", oneLine(m.Description))
		}
		if len(m.InputSchema) == 0 {
			fmt.Fprintf(&b, "    %s: (): Promise<%sOutput> =>\n", fn, exportName(m.Name))
			fmt.Fprintf(&b, "      dispatch(%q, undefined) as Promise<%sOutput>,\n", slotPath, exportName(m.Name))
			continue
		}
		fmt.Fprintf(&b, "    %s: (input: %sInput): Promise<%sOutput> =>\n", fn, exportName(m.Name), exportName(m.Name))
		fmt.Fprintf(&b, "      dispatch(%q, input) as Promise<%sOutput>,\n", slotPath, exportName(m.Name))
	}
	b.WriteString("  }\n}\n")
	return b.String(), nil
}

// typeBlock emits an interface for an object schema, or a type alias otherwise.
// An absent schema becomes void, so a method with no input still type-checks.
func typeBlock(name string, raw json.RawMessage) (string, error) {
	if len(raw) == 0 {
		return fmt.Sprintf("export type %s = void\n\n", name), nil
	}
	var s schema
	if err := json.Unmarshal(raw, &s); err != nil {
		return "", err
	}
	if s.Type == "object" && len(s.Properties) > 0 {
		body, err := objectBody(&s, 1)
		if err != nil {
			return "", err
		}
		doc := ""
		if s.Description != "" {
			doc = fmt.Sprintf("/** %s */\n", oneLine(s.Description))
		}
		return fmt.Sprintf("%sexport interface %s %s\n\n", doc, name, body), nil
	}
	t, err := tsType(&s, 0)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("export type %s = %s\n\n", name, t), nil
}

// schema is the JSON-Schema subset these descriptors actually use. Verified
// against every published method: no ref/defs, no oneOf/anyOf/allOf, no enum — so
// this is a subset by EVIDENCE, not by hope. An unmodelled construct is reported
// rather than silently emitted as any, which would put a wrong type at a call site.
type schema struct {
	Type                 string             `json:"type"`
	Description          string             `json:"description"`
	Properties           map[string]*schema `json:"properties"`
	Required             []string           `json:"required"`
	Items                *schema            `json:"items"`
	AdditionalProperties *addlProps         `json:"additionalProperties"`
	Ref                  string             `json:"$ref"`
	OneOf                []*schema          `json:"oneOf"`
	AnyOf                []*schema          `json:"anyOf"`
	AllOf                []*schema          `json:"allOf"`
}

// addlProps models JSON Schema `additionalProperties`, which is EITHER a bool or a
// schema. The bool form is the common one in these descriptors (`false` = a closed
// object) and is not a map at all — decoding it as a schema is what made the first
// real run fail. Only the schema form becomes a TS Record.
type addlProps struct {
	Allowed bool
	Schema  *schema
}

func (a *addlProps) UnmarshalJSON(b []byte) error {
	switch strings.TrimSpace(string(b)) {
	case "false":
		a.Allowed = false
		return nil
	case "true":
		a.Allowed = true
		return nil
	}
	var s schema
	if err := json.Unmarshal(b, &s); err != nil {
		return err
	}
	a.Allowed, a.Schema = true, &s
	return nil
}

func objectBody(s *schema, depth int) (string, error) {
	names := make([]string, 0, len(s.Properties))
	for n := range s.Properties {
		names = append(names, n)
	}
	sort.Strings(names)

	req := map[string]bool{}
	for _, r := range s.Required {
		req[r] = true
	}

	pad := strings.Repeat("  ", depth)
	var b strings.Builder
	b.WriteString("{\n")
	for _, n := range names {
		p := s.Properties[n]
		t, err := tsType(p, depth)
		if err != nil {
			return "", fmt.Errorf("property %q: %w", n, err)
		}
		if p.Description != "" {
			fmt.Fprintf(&b, "%s/** %s */\n", pad, oneLine(p.Description))
		}
		opt := "?"
		if req[n] {
			opt = ""
		}
		fmt.Fprintf(&b, "%s%s%s: %s\n", pad, tsPropName(n), opt, t)
	}
	fmt.Fprintf(&b, "%s}", strings.Repeat("  ", depth-1))
	return b.String(), nil
}

func tsType(s *schema, depth int) (string, error) {
	if s == nil {
		return "unknown", nil
	}
	switch {
	case s.Ref != "":
		return "", fmt.Errorf("$ref is not supported (descriptors inline their schemas)")
	case len(s.OneOf) > 0 || len(s.AnyOf) > 0 || len(s.AllOf) > 0:
		return "", fmt.Errorf("oneOf/anyOf/allOf are not supported")
	}
	switch s.Type {
	case "string":
		return "string", nil
	case "number", "integer":
		return "number", nil
	case "boolean":
		return "boolean", nil
	case "array":
		inner, err := tsType(s.Items, depth)
		if err != nil {
			return "", err
		}
		return inner + "[]", nil
	case "object":
		if len(s.Properties) > 0 {
			return objectBody(s, depth+1)
		}
		// A map is the SCHEMA form of additionalProperties. `false` (a closed object
		// with no declared properties) carries no key type, so it stays unknown.
		if ap := s.AdditionalProperties; ap != nil && ap.Schema != nil {
			inner, err := tsType(ap.Schema, depth)
			if err != nil {
				return "", err
			}
			return "Record<string, " + inner + ">", nil
		}
		return "Record<string, unknown>", nil
	case "":
		return "unknown", nil
	default:
		return "", fmt.Errorf("unsupported schema type %q", s.Type)
	}
}

// exportName turns a kebab wire name into PascalCase. The WIRE name is
// authoritative (it comes from ToKebab in the publish reflection) — never derive
// it from a Go identifier.
func exportName(kebab string) string {
	parts := strings.FieldsFunc(kebab, func(r rune) bool { return r == '-' || r == '_' || r == '.' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// tsPropName quotes a property name that is not a bare JS identifier.
func tsPropName(n string) string {
	ok := n != ""
	for i, r := range n {
		isAlpha := r == '_' || r == '$' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z')
		isDigit := r >= '0' && r <= '9'
		if !(isAlpha || (i > 0 && isDigit)) {
			ok = false
			break
		}
	}
	if ok {
		return n
	}
	return fmt.Sprintf("%q", n)
}

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "*/", "*!/")
	return strings.Join(strings.Fields(s), " ")
}

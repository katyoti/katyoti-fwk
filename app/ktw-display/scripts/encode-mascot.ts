// encode-mascot — regenerate src/widgets/_lib/mascot-data.ts from a PNG.
//
// The loading screen (render-loading.ts) embeds the KaTyoti mascot as a
// base64 data URI so it is fully self-contained (renders identically in
// dev and prod, no static-asset route, no second network round-trip).
// To swap the mascot, drop a new PNG at media/katyoti_loading.png (or pass
// a path) and run, from app/ktw-display:
//     bun run scripts/encode-mascot.ts [path-to-png]
// then rebuild the binary (make ktw-display).
//
// base64 of a PNG is LOSSLESS — full image quality is preserved.

// Paths are resolved relative to the CWD (run from app/ktw-display).
const src = Bun.argv[2] ?? '../../media/katyoti_loading.png'
// The mascot lives in ktw-display-lib so both the HTML loading screen
// (render-loading.ts) and the React <LoadingView> can share it.
const dst = '../ktw-display-lib/src/ui-core/loading/mascot-data.ts'

const bytes = await Bun.file(src).arrayBuffer()
if (bytes.byteLength === 0) {
  console.error(`encode-mascot: ${src} is empty or missing`)
  process.exit(1)
}
const b64 = Buffer.from(bytes).toString('base64')
const out = `// AUTO-GENERATED by scripts/encode-mascot.ts — do not edit by hand.
// Source image: media/katyoti_loading.png (run \`bun run scripts/encode-mascot.ts\` to refresh).
export const MASCOT_DATA_URI = 'data:image/png;base64,${b64}'
`
await Bun.write(dst, out)
console.log(`encode-mascot: wrote ${dst} (${(bytes.byteLength / 1024).toFixed(1)} KB png, ${b64.length} b64 chars) from ${src}`)

// Command gentextmetrics writes api/textmetrics_gen.go: the advance width of
// each glyph a draw.io label commonly uses, per 1000 em, in the Helvetica /
// Arial metric (the font draw.io's default Helvetica resolves to). It runs
// once, through `go generate` in api/; the engine never reads a font file.
//
// The source is an Arial-metric font: Liberation Sans (SIL Open Font
// License) when it is found, else the Arial of the machine. The two share
// every advance with Adobe's core-14 Helvetica AFM metrics, which the api
// tests pin on reference glyphs, so the table is the same whichever was
// read.
//
//	go run ../internal/gentextmetrics -o textmetrics_gen.go [-regular f.ttf -bold f.ttf]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"runtime"

	"golang.org/x/image/font"
	"golang.org/x/image/font/sfnt"
	"golang.org/x/image/math/fixed"
)

// extra are the glyphs outside Latin-1 that labels use: dashes, quotes,
// bullets, arrows, the euro and the French ligatures.
var extra = []rune{
	0x0152, 0x0153, 0x0178, 0x2009, 0x2010, 0x2011, 0x2013, 0x2014, 0x2018, 0x2019,
	0x201A, 0x201C, 0x201D, 0x201E, 0x2022, 0x2026, 0x202F, 0x2030, 0x2039, 0x203A,
	0x20AC, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x2264, 0x2265,
}

func main() {
	out := flag.String("o", "textmetrics_gen.go", "output Go file")
	regular := flag.String("regular", "", "regular face (default: Liberation Sans, else Arial)")
	bold := flag.String("bold", "", "bold face (default: Liberation Sans Bold, else Arial Bold)")
	flag.Parse()
	if *regular == "" || *bold == "" {
		r, b, err := findFaces()
		if err != nil {
			fail(err)
		}
		if *regular == "" {
			*regular = r
		}
		if *bold == "" {
			*bold = b
		}
	}
	reg, regName, err := advances(*regular)
	if err != nil {
		fail(err)
	}
	bld, bldName, err := advances(*bold)
	if err != nil {
		fail(err)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gentextmetrics; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package api\n\n")
	fmt.Fprintf(&b, "// Advance widths per 1000 em in the Helvetica / Arial metric, read from\n")
	fmt.Fprintf(&b, "// %q and %q.\n", regName, bldName)
	fmt.Fprintf(&b, "// Regenerate with `go generate` in this package.\n\n")
	write := func(name string, m map[rune]int) {
		fmt.Fprintf(&b, "var %s = map[rune]int16{\n", name)
		for _, r := range runes() {
			if w, ok := m[r]; ok {
				fmt.Fprintf(&b, "\t%#04x: %d, // %q\n", r, w, r)
			}
		}
		fmt.Fprintf(&b, "}\n\n")
	}
	write("helveticaRegular", reg)
	write("helveticaBold", bld)
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fail(err)
	}
}

func runes() []rune {
	var rs []rune
	for r := rune(0x20); r <= 0x7E; r++ {
		rs = append(rs, r)
	}
	for r := rune(0xA0); r <= 0xFF; r++ {
		rs = append(rs, r)
	}
	return append(rs, extra...)
}

// advances reads each rune's advance from a TrueType face, per 1000 em.
func advances(path string) (map[rune]int, string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, "", err
	}
	f, err := sfnt.Parse(data)
	if err != nil {
		return nil, "", fmt.Errorf("%s: %w", path, err)
	}
	var buf sfnt.Buffer
	name, _ := f.Name(&buf, sfnt.NameIDFull)
	if name == "" {
		name = filepath.Base(path)
	}
	upem := f.UnitsPerEm()
	m := map[rune]int{}
	for _, r := range runes() {
		gi, err := f.GlyphIndex(&buf, r)
		if err != nil || gi == 0 {
			continue
		}
		adv, err := f.GlyphAdvance(&buf, gi, fixed.I(int(upem)), font.HintingNone)
		if err != nil {
			continue
		}
		units := float64(adv) / 64
		m[r] = int(math.Round(units * 1000 / float64(upem)))
	}
	return m, name, nil
}

// findFaces looks for Liberation Sans first, then the system Arial.
func findFaces() (string, string, error) {
	var dirs []string
	if d := os.Getenv("KTW_FONT_DIR"); d != "" {
		dirs = append(dirs, d)
	}
	switch runtime.GOOS {
	case "windows":
		dirs = append(dirs, filepath.Join(os.Getenv("WINDIR"), "Fonts"), filepath.Join(os.Getenv("LOCALAPPDATA"), "Microsoft", "Windows", "Fonts"))
	case "darwin":
		dirs = append(dirs, "/Library/Fonts", "/System/Library/Fonts/Supplemental")
	default:
		dirs = append(dirs, "/usr/share/fonts/truetype/liberation", "/usr/share/fonts/liberation-sans", "/usr/share/fonts/truetype/msttcorefonts")
	}
	pairs := [][2]string{
		{"LiberationSans-Regular.ttf", "LiberationSans-Bold.ttf"},
		{"arial.ttf", "arialbd.ttf"},
		{"Arial.ttf", "Arial Bold.ttf"},
	}
	for _, p := range pairs {
		for _, d := range dirs {
			r, b := filepath.Join(d, p[0]), filepath.Join(d, p[1])
			if exists(r) && exists(b) {
				return r, b, nil
			}
		}
	}
	return "", "", fmt.Errorf("no Arial-metric font found (Liberation Sans or Arial): pass -regular and -bold, or set KTW_FONT_DIR")
}

func exists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gentextmetrics:", err)
	os.Exit(1)
}

var _ = strategies.StrategyDef[engine.MachineFactory]{} // keep strategies import

func registerSimulatorForWkflow(t *testing.T) {
	t.Helper()
	_, createFn := simulator.MachineStrategyDef.Strategy.NewTypeConfig()
	raw, err := createFn(context.Background())
	if err != nil {
		t.Fatalf("simulator factory: %v", err)
	}
	td := simulator.MachineStrategyDef.Strategy.CreateTypeDef("simulator", raw)
	_ = engine.MachineDomain.Types.Contribute(td)
}

// TestSpawn_HandlerResumesWithChildOutput (UC-032) — the spawn handler waits
// for `child.<name>.done` then resumes the parent workflow. The child's
// output is bound into the workflow state's `Children` map so subsequent
// steps can reference it.
//
// Single-spawn workflow: simulator emits a recognisable output; assert it
// surfaces in the workflow's terminal result keyed by the spawn step name.
func TestSpawn_HandlerResumesWithChildOutput(t *testing.T) {
	registerSimulatorForWkflow(t)

	cfg := map[string]any{
		"steps": []any{
			map[string]any{
				"name": "the-child",
				"task": map[string]any{
					"type":        "simulator",
					"duration_ms": 0,
					"output":      map[string]any{"summary": "uc032-payload"},
				},
			},
			map[string]any{
				"kind":  "return",
				"value": "${results}",
			},
		},
	}

	bus := engine.NewMemoryEventBus()
	channel := engine.NewChannel(bus)
	ctx := withLocalSpawner(channel)

	factory := &workflowFactory{}
	m, err := factory.CreateMachine(ctx, &taskapi.TaskExecRequest{Config: cfg})
	if err != nil {
		t.Fatalf("CreateMachine: %v", err)
	}

	exec := engine.NewExecutor(m, channel, nil)

	runCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	result, err := exec.Run(runCtx, engine.Event{Type: "start"})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if result.Next != engine.Done {
		t.Fatalf("Next = %v, want Done (was workflow output: %#v)", result.Next, result.Output)
	}

	out, _ := result.Output.(map[string]any)
	if out == nil {
		t.Fatalf("workflow output not a map: %#v", result.Output)
	}
	childOutput, _ := out["the-child"].(map[string]any)
	if childOutput == nil {
		t.Fatalf("output[the-child] = %#v, want map (the spawn handler should have bound child.done's Output into results[the-child])", out["the-child"])
	}
	if childOutput["summary"] != "uc032-payload" {
		t.Errorf("child output summary = %v, want uc032-payload", childOutput["summary"])
	}
}

// TestLifecycleEmissions (UC-035) — the workflow emits
// `workflow.<runID>.started` exactly once (on the first step) and
// `workflow.<runID>.done` exactly once (on terminal success).
//
// Failure-path emission (`workflow.<runID>.failed`) is covered by the
// existing parallel-fail-fast tests; this test focuses on the success path.
func TestLifecycleEmissions(t *testing.T) {
	registerSimulatorForWkflow(t)

	cfg := map[string]any{
		"steps": []any{
			map[string]any{
				"name": "leaf",
				"task": map[string]any{
					"type":        "simulator",
					"duration_ms": 0,
					"output":      "done",
				},
			},
			map[string]any{"kind": "return", "value": "results"},
		},
	}

	bus := engine.NewMemoryEventBus()
	channel := engine.NewChannel(bus)
	ctx := withLocalSpawner(channel)

	// Subscribe to wildcard workflow.* topics. We don't know the runID up
	// front, so we subscribe to glob patterns. MemoryEventBus.Subscribe is
	// pattern-aware (path.Match in matchesCondition); for the bus itself,
	// we register two known prefixes via per-emit topics generated by
	// WorkflowStartedTopic/WorkflowDoneTopic with the runID we'll set.
	//
	// Simplest path: pre-set the executor's runID, then subscribe to the
	// exact topics.
	const runID = "run-uc035"

	startedCh := make(chan struct{}, 4)
	doneCh := make(chan any, 4)
	bus.Subscribe(engine.WorkflowStartedTopic(runID), func(_ string, _ any) {
		select {
		case startedCh <- struct{}{}:
		default:
		}
	})
	bus.Subscribe(engine.WorkflowDoneTopic(runID), func(_ string, payload any) {
		select {
		case doneCh <- payload:
		default:
		}
	})

	factory := &workflowFactory{}
	m, err := factory.CreateMachine(ctx, &taskapi.TaskExecRequest{Config: cfg})
	if err != nil {
		t.Fatalf("CreateMachine: %v", err)
	}
	exec := engine.NewExecutor(m, channel, nil)
	exec.SetRunID(runID)

	runCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	if _, err := exec.Run(runCtx, engine.Event{Type: "start"}); err != nil {
		t.Fatalf("Run: %v", err)
	}

	select {
	case <-startedCh:
		// good
	case <-time.After(500 * time.Millisecond):
		t.Fatal("UC-035: workflow.<runID>.started not emitted")
	}

	// Exactly one started — drain the channel and assert no second event.
	select {
	case <-startedCh:
		t.Error("UC-035: workflow.<runID>.started emitted more than once")
	case <-time.After(50 * time.Millisecond):
	}

	select {
	case payload := <-doneCh:
		evt, ok := payload.(*engine.WorkflowDoneEvent)
		if !ok {
			t.Fatalf("UC-035: done payload type = %T, want *WorkflowDoneEvent", payload)
		}
		if evt.RunID != runID {
			t.Errorf("done.RunID = %q, want %q", evt.RunID, runID)
		}
	case <-time.After(500 * time.Millisecond):
		t.Fatal("UC-035: workflow.<runID>.done not emitted")
	}
}

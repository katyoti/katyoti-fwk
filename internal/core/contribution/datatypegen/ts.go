// TSNames lists the data-types also rendered as TypeScript, in registry order.
func TSNames() []string {
	var out []string
	for _, s := range Registry {
		if s.TS {
			out = append(out, s.Name)
		}
	}
	return out
}

// RenderTS returns the TypeScript module for one registered data-type: its
// root as an exported interface, from the same AST the DSL document is
// rendered from, so the GUI's type cannot drift from the Go struct. Byte-stable
// (fields sorted by name).
func RenderTS(name string) ([]byte, error) {
	var src *Source
	for i := range Registry {
		if Registry[i].Name == name && Registry[i].TS {
			src = &Registry[i]
		}
	}
	if src == nil {
		return nil, fmt.Errorf("datatypegen: no TypeScript source named %q (have %v)", name, TSNames())
	}
	return RenderTSAs(*src, Header{
		Tool:       "tools/gen-data-type",
		Regenerate: "`go generate ./internal/core/contribution/`",
	})
}

// RenderTSAs renders a type that is not a system data-type — one an
// extension declares and its TypeScript reader imports — with the header that
// says how to regenerate it. The extension holds the file current with its
// own test, exactly as it does for the DSL document RenderAs writes.
func RenderTSAs(src Source, h Header) ([]byte, error) {
	root, err := src.AST()
	if err != nil {
		return nil, fmt.Errorf("datatypegen %s: %w", src.Name, err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// GENERATED by %s from %s — DO NOT EDIT.\n", h.Tool, src.Origin)
	b.WriteString("// The Go type is the one source of this contract: change the struct, then\n")
	fmt.Fprintf(&b, "// %s. A test refuses a stale file.\n\n", h.Regenerate)
	writeDoc(&b, strings.TrimSpace(src.Description), "")
	fmt.Fprintf(&b, "export interface %s ", src.Root)
	writeObject(&b, root, "")
	b.WriteString("\n")
	return []byte(b.String()), nil
}

func writeDoc(b *strings.Builder, text, indent string) {
	if text == "" {
		return
	}
	text = strings.ReplaceAll(text, "*/", "*\\/")
	lines := strings.Split(text, "\n")
	if len(lines) == 1 {
		fmt.Fprintf(b, "%s/** %s */\n", indent, lines[0])
		return
	}
	fmt.Fprintf(b, "%s/**\n", indent)
	for _, l := range lines {
		fmt.Fprintf(b, "%s * %s\n", indent, strings.TrimRight(l, " "))
	}
	fmt.Fprintf(b, "%s */\n", indent)
}

// writeObject writes `{ field?: T … }` for an object with fields.
func writeObject(b *strings.Builder, t *schemaapi.Type, indent string) {
	names := make([]string, 0, len(t.Fields))
	for n := range t.Fields {
		names = append(names, n)
	}
	sort.Strings(names)
	b.WriteString("{\n")
	inner := indent + "  "
	for _, n := range names {
		f := t.Fields[n]
		writeDoc(b, f.Description, inner)
		opt := ""
		if f.Optional {
			opt = "?"
		}
		fmt.Fprintf(b, "%s%s%s: %s\n", inner, n, opt, tsType(f, inner))
	}
	fmt.Fprintf(b, "%s}", indent)
}

func tsRef(r *schemaapi.TypeRef, indent string) string {
	if r == nil {
		return "unknown"
	}
	if r.Name != "" {
		return r.Name
	}
	return tsType(r.Inline, indent)
}

func tsType(t *schemaapi.Type, indent string) string {
	if t == nil {
		return "unknown"
	}
	switch t.Kind {
	case schemaapi.KindString:
		if len(t.Enum) > 0 {
			var parts []string
			for _, e := range t.Enum {
				parts = append(parts, fmt.Sprintf("%q", fmt.Sprint(e)))
			}
			return strings.Join(parts, " | ")
		}
		return "string"
	case schemaapi.KindNumber:
		return "number"
	case schemaapi.KindBoolean:
		return "boolean"
	case schemaapi.KindNull:
		return "null"
	case schemaapi.KindArray:
		el := tsRef(t.Items, indent)
		if strings.ContainsAny(el, " |{") {
			el = "(" + el + ")"
		}
		return el + "[]"
	case schemaapi.KindChoice:
		var parts []string
		for _, c := range t.Cases {
			parts = append(parts, tsRef(c, indent))
		}
		return strings.Join(parts, " | ")
	case schemaapi.KindObject:
		if len(t.Fields) == 0 {
			if t.Catchall != nil {
				return "Record<string, " + tsRef(t.Catchall, indent) + ">"
			}
			return "Record<string, unknown>"
		}
		var b strings.Builder
		writeObject(&b, t, indent)
		return b.String()
	case schemaapi.KindLink, schemaapi.KindTree:
		if t.Target != "" {
			return t.Target
		}
		return "unknown"
	default:
		return "unknown"
	}
}

// MediaTypesTSName is the generated media-types module's file name.
const MediaTypesTSName = "media-types"

// RenderMediaTypesTS returns the GUI's media-types module: the media types
// display names and the document-kind table, from internal/core/render — the
// frontend holds no copy of either.
func RenderMediaTypesTS() []byte {
	var b strings.Builder
	b.WriteString("// GENERATED by tools/gen-data-type from internal/core/render/mediatype.go — DO NOT EDIT.\n")
	b.WriteString("// The Go table is the one source: change it, then\n")
	b.WriteString("// `go generate ./internal/core/contribution/`. A test refuses a stale file.\n\n")
	named := render.Named()
	names := make([]string, 0, len(named))
	for n := range named {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "export const MEDIA_TYPE_%s = %q\n", strings.ToUpper(n), named[n])
	}
	b.WriteString("\n/** The render.Def kinds that name a document, and the media type each is.\n")
	b.WriteString(" *  Every other kind is a ui-component (MEDIA_TYPE_UI). */\n")
	b.WriteString("export const DOCUMENT_KINDS: Readonly<Record<string, string>> = {\n")
	kinds := render.DocumentKinds()
	keys := make([]string, 0, len(kinds))
	for k := range kinds {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "  %q: %q,\n", k, kinds[k])
	}
	b.WriteString("}\n\n")
	b.WriteString("/** The media type a render.Def kind displays as (render.MediaTypeForKind). */\n")
	b.WriteString("export function mediaTypeForKind(kind: string | undefined): string {\n")
	b.WriteString("  if (!kind) return ''\n")
	b.WriteString("  return DOCUMENT_KINDS[kind] ?? MEDIA_TYPE_UI\n")
	b.WriteString("}\n")
	return []byte(b.String())
}

package datatypegen

import (
	"bytes"
	"strings"
	"testing"

	ktwreflect "github.com/katyoti/katyoti-fwk/internal/core/reflect"
	schemaapi "github.com/katyoti/katyoti-fwk/internal/core/schema/api"
)

type sampleAddress struct {
	Street string `json:"street" jsonschema:"title=Street"`
	City   string `json:"city,omitempty" jsonschema:"title=City"`
}

type sampleRoot struct {
	Name string         `json:"name" jsonschema:"title=Name,description=Who"`
	Home sampleAddress  `json:"home" jsonschema:"title=Home"`
	Work *sampleAddress `json:"work,omitempty" jsonschema:"title=Work"`
}

func sampleSource(named bool) Source {
	src := Source{
		Name:        "sample",
		Version:     "1.0.0",
		Root:        "Sample",
		Description: "A sample.\n",
		Origin:      "sampleRoot (datatypegen_test.go)",
		AST:         func() (*schemaapi.Type, error) { return ktwreflect.TypeAST[sampleRoot]() },
	}
	if named {
		src.Named = []NamedType{{Name: "Address", Description: "A postal address.",
			AST: func() (*schemaapi.Type, error) { return ktwreflect.TypeAST[sampleAddress]() }}}
	}
	return src
}

var sampleHeader = Header{Tool: "the test", Regenerate: "`go test`", URI: "test:/data-type/sample"}

// A rendered document says where it comes from, puts its header keys first
// in a reader's order, and is byte-stable: rendering twice gives the same
// bytes, so a stale-file test compares them.
func TestRenderAsIsHeaderedOrderedAndStable(t *testing.T) {
	a, err := RenderAs(sampleSource(false), sampleHeader)
	if err != nil {
		t.Fatal(err)
	}
	b, _ := RenderAs(sampleSource(false), sampleHeader)
	if !bytes.Equal(a, b) {
		t.Fatal("two renders of one source differ")
	}
	s := string(a)
	for _, want := range []string{"# GENERATED by the test from sampleRoot (datatypegen_test.go)", "URI: test:/data-type/sample", "description: Who"} {
		if !strings.Contains(s, want) {
			t.Errorf("render lacks %q:\n%s", want, s)
		}
	}
	order := []string{"$schema:", "name: sample", "version: 1.0.0", "root: Sample", "description:", "types:"}
	at := -1
	for _, k := range order {
		i := strings.Index(s, k)
		if i < at {
			t.Fatalf("%q out of order:\n%s", k, s)
		}
		at = i
	}
}

// A named type is kept under its name in `types:`, and every object of
// exactly its fields refers to it, keeping the field's own optionality.
func TestANamedTypeIsHoistedAndReferred(t *testing.T) {
	out, err := RenderAs(sampleSource(true), sampleHeader)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	if !strings.Contains(s, "  Address:\n") || !strings.Contains(s, "A postal address.") {
		t.Fatalf("Address is not a named type:\n%s", s)
	}
	if strings.Count(s, "type: Address") != 2 {
		t.Fatalf("home and work do not both refer to Address:\n%s", s)
	}
	if strings.Count(s, "street:") != 1 {
		t.Fatalf("the address fields are still inline somewhere:\n%s", s)
	}
}

// Render knows only the registry; an unknown name says which names it has.
func TestRenderRefusesAnUnregisteredName(t *testing.T) {
	if _, err := Render("no-such-type"); err == nil || !strings.Contains(err.Error(), "no registered source") {
		t.Fatalf("err = %v", err)
	}
	for _, n := range Names() {
		if _, err := Render(n); err != nil {
			t.Errorf("registered %s does not render: %v", n, err)
		}
	}
}

// The TypeScript twin renders the same Go type as an interface.
func TestRenderTSAsWritesAnInterface(t *testing.T) {
	out, err := RenderTSAs(sampleSource(false), sampleHeader)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	for _, want := range []string{"Sample", "name: string", "work?:"} {
		if !strings.Contains(s, want) {
			t.Errorf("TS lacks %q:\n%s", want, s)
		}
	}
}
